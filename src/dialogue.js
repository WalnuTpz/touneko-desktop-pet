  function normalizeAssetName(name) {
    return String(name || "").replace(/^\d+_/, "").trim();
  }

  function messagesForAsset(name) {
    const normalized = normalizeAssetName(name);
    return ACTION_DIALOGUE[normalized] || ["看我的小表演～"];
  }

  function dialogueForAsset(name, random = Math.random) {
    const messages = messagesForAsset(name);
    const index = Math.min(
      messages.length - 1,
      Math.floor(Math.max(0, Math.min(0.999999, random())) * messages.length),
    );
    return messages[index];
  }

